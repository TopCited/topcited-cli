import { describe, expect, test } from "bun:test";
import { parseSums, renderFormula } from "../scripts/render-formula";

const template = await Bun.file("Formula/topcited.rb").text();
const h = (c: string) => c.repeat(64);
const SUMS = [
  `${h("a")}  topcited-darwin-arm64`,
  `${h("b")}  topcited-darwin-x64`,
  `${h("c")}  topcited-linux-arm64`,
  `${h("d")} *topcited-linux-x64`,
  `${h("e")}  topcited-windows-x64.exe`,
].join("\n");

describe("Homebrew formula", () => {
  test("fills the version and each platform's sha256 from SHA256SUMS", () => {
    const out = renderFormula(template, "v1.2.3", parseSums(SUMS));
    expect(out).not.toMatch(/\{\{/);
    expect(out).toStartWith("# Generated by TopCited/topcited-cli release.yml for v1.2.3. Do not edit.\nclass Topcited < Formula");
    expect(out).toContain('version "1.2.3"');
    expect(out).toContain("releases/download/v1.2.3/topcited-darwin-arm64\"\n      sha256 \"" + h("a"));
    expect(out).toContain("releases/download/v1.2.3/topcited-linux-x64\"\n      sha256 \"" + h("d"));
    expect(out).not.toContain(h("e")); // no Windows in a brew formula
  });

  test("refuses a missing or malformed checksum", () => {
    const partial = parseSums(SUMS.split("\n").slice(1).join("\n"));
    expect(() => renderFormula(template, "1.2.3", partial)).toThrow("topcited-darwin-arm64");
    expect(() => renderFormula(template, "1.2.3", new Map([...parseSums(SUMS), ["topcited-linux-x64", "xyz"]]))).toThrow();
  });

  test("refuses prerelease versions", () => {
    expect(() => renderFormula(template, "v1.2.3-rc.1", parseSums(SUMS))).toThrow("not a release version");
  });
});
