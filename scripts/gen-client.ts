// Regenerate the typed client from the public OpenAPI contract.
//
//   bun run gen:client                  # from the committed openapi.public.json
//   bun run gen:client --fetch [url]    # refresh the snapshot first (default: prod)
import openapiTS, { astToString } from "openapi-typescript";

const PROD_SPEC_URL = "https://api.topcited.ai/api/v1/openapi.public.json";
const SNAPSHOT = new URL("../openapi.public.json", import.meta.url);
const OUT = new URL("../src/generated/schema.d.ts", import.meta.url);
const OPS_OUT = new URL("../src/generated/operations.ts", import.meta.url);

const args = process.argv.slice(2);
const fetchIdx = args.indexOf("--fetch");
if (fetchIdx !== -1) {
  const url = args[fetchIdx + 1] ?? PROD_SPEC_URL;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  const spec = await res.json();
  await Bun.write(SNAPSHOT, JSON.stringify(spec, null, 2) + "\n");
  console.error(`snapshot refreshed from ${url}`);
}

export async function generate(): Promise<string> {
  const spec = await Bun.file(SNAPSHOT).json();
  // Fields with a server default are optional to send (requests) and may be absent (responses).
  const ast = await openapiTS(spec, { defaultNonNullable: false });
  return (
    "// GENERATED by scripts/gen-client.ts from openapi.public.json. Do not edit.\n" +
    astToString(ast)
  );
}

/** `[METHOD, path, operationId]` for every public operation; `doctor` diffs it against the server's spec. */
export async function generateOperations(): Promise<string> {
  const spec = await Bun.file(SNAPSHOT).json();
  const ops: string[] = [];
  for (const [path, item] of Object.entries<Record<string, { operationId?: string }>>(spec.paths)) {
    for (const [method, op] of Object.entries(item)) {
      if (op?.operationId) ops.push(`  [${JSON.stringify(method.toUpperCase())}, ${JSON.stringify(path)}, ${JSON.stringify(op.operationId)}],`);
    }
  }
  return (
    "// GENERATED by scripts/gen-client.ts from openapi.public.json. Do not edit.\n" +
    "export const OPERATIONS: ReadonlyArray<readonly [method: string, path: string, operationId: string]> = [\n" +
    ops.join("\n") +
    "\n];\n"
  );
}

if (import.meta.main) {
  await Bun.write(OUT, await generate());
  await Bun.write(OPS_OUT, await generateOperations());
  console.error(`wrote ${OUT.pathname} and ${OPS_OUT.pathname}`);
}
