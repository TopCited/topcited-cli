// Render Formula/topcited.rb for a release from its SHA256SUMS.
//
//   bun run scripts/render-formula.ts --version 0.1.0 --sums dist/SHA256SUMS > topcited.rb
const TEMPLATE = new URL("../Formula/topcited.rb", import.meta.url);

/** Placeholder → release asset whose sha256 fills it. */
const ASSETS: Record<string, string> = {
  SHA256_DARWIN_ARM64: "topcited-darwin-arm64",
  SHA256_DARWIN_X64: "topcited-darwin-x64",
  SHA256_LINUX_ARM64: "topcited-linux-arm64",
  SHA256_LINUX_X64: "topcited-linux-x64",
};

export function parseSums(text: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const line of text.split("\n")) {
    const [hash, name] = line.trim().split(/\s+/);
    if (hash && name) out.set(name.replace(/^\*/, ""), hash.toLowerCase());
  }
  return out;
}

export function renderFormula(template: string, version: string, sums: Map<string, string>): string {
  const v = version.replace(/^v/, "");
  if (!/^\d+\.\d+\.\d+$/.test(v)) throw new Error(`not a release version: ${version}`);
  let out = template.replaceAll("{{VERSION}}", v);
  for (const [key, asset] of Object.entries(ASSETS)) {
    const hash = sums.get(asset);
    if (!hash || !/^[0-9a-f]{64}$/.test(hash)) throw new Error(`SHA256SUMS has no valid sha256 for ${asset}`);
    out = out.replaceAll(`{{${key}}}`, hash);
  }
  const left = out.match(/\{\{\w+\}\}/);
  if (left) throw new Error(`unfilled placeholder ${left[0]}`);
  // The template's own header comment describes the template, not the output.
  return out.replace(/^(#[^\n]*\n)+/, `# Generated by TopCited/topcited-cli release.yml for v${v}. Do not edit.\n`);
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const get = (f: string) => {
    const i = args.indexOf(f);
    const v = i === -1 ? undefined : args[i + 1];
    if (!v) throw new Error(`missing ${f}`);
    return v;
  };
  const sums = parseSums(await Bun.file(get("--sums")).text());
  process.stdout.write(renderFormula(await Bun.file(TEMPLATE).text(), get("--version"), sums));
}
